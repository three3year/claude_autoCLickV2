"""舞台: 執行器與並行協調器之間的唯一介面.

`舞台`＝前景視窗與滑鼠的獨佔權。同一時間只有一份流程持有
(見舊專案 ADR-0004)。並行執行本輪未移植 (原實作有 bug、測試不全,
留待日後重做); 本接縫與其測試保留, 執行器不注入時完全走單流程路徑。

執行器對「切視窗」這件事一無所知, 只知道自己要取得與讓出;
把`綁定視窗`帶到最前面是`舞台`實作的責任。

每份流程拿到的是**自己專屬**的一個 Stage 實例 (它知道自己是哪份流程、
綁定哪個視窗), 所以這些方法都不必傳流程識別。

單流程執行時不注入 (`Runner(stage=None)`), 執行器完全走原本的路徑。
"""


class Stage:
    """舞台介面. 測試用假實作見 tests/harness.py."""

    def acquire(self):
        """阻塞直到本流程持有舞台, 並確保`綁定視窗`已在最前面.

        回傳 False 代表整場執行已結束 (全部停止), 呼叫端應立刻收工。
        """
        raise NotImplementedError

    def release(self):
        """交出舞台. 只在進入`等待`步驟時呼叫——這是唯一的`讓出點`."""
        raise NotImplementedError

    def cancel(self):
        """喚醒正卡在 acquire() 的本流程, 讓它立刻回傳 False.

        由執行器的 stop() 呼叫。沒有這個方法, 一份正在`排隊`的流程被停掉時
        會永遠卡在 acquire 裡, 連 leave() 都執行不到——其他流程跟著陪葬。
        必須可重複呼叫, 也必須能在沒有人阻塞時呼叫。
        """
        raise NotImplementedError

    def leave(self):
        """本流程退出輪轉 (跑完、出錯、視窗消失). 必須可重複呼叫.

        任何流程退出都一定要交還舞台, 否則其他流程會永久卡住。
        也可能在「已經 release 但還沒重新 acquire」的狀態下被呼叫
        (`等待`途中被急停), 實作必須容許此時的 leave。
        """
        raise NotImplementedError
